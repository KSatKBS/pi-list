#!/usr/bin/env python3
"""Generate the KS X 1001 (EUC-KR) -> Unicode lookup table used by the CEA-708 decoder.

Usage: python3 scripts/generate_ksx1001_table.py > \
    cpp/libs/analysis/lib/src/ebu/list/analysis/handlers/cea708/ksx1001_table.cpp
"""

ROWS = range(0xA1, 0xFF)


def main():
    entries = []
    for lead in ROWS:
        for trail in ROWS:
            try:
                ch = bytes([lead, trail]).decode("euc_kr")
                entries.append(ord(ch) if len(ch) == 1 else 0)
            except UnicodeDecodeError:
                entries.append(0)

    print("// Generated by scripts/generate_ksx1001_table.py - DO NOT EDIT")
    print("// KS X 1001 (EUC-KR, 94x94 rows/cells 0xA1-0xFE) to Unicode BMP code points. 0 = unmapped.")
    print()
    print('#include "ebu/list/analysis/handlers/cea708/ksx1001.h"')
    print()
    print("namespace ebu_list::analysis::cea708::detail")
    print("{")
    print("    extern const char16_t ksx1001_table[ksx1001_rows * ksx1001_rows] = {")
    for i in range(0, len(entries), 12):
        chunk = ", ".join(f"0x{v:04X}" for v in entries[i : i + 12])
        print(f"        {chunk},")
    print("    };")
    print("} // namespace ebu_list::analysis::cea708::detail")


if __name__ == "__main__":
    main()
